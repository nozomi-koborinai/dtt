import 'dart:convert';
import 'dart:io';

import 'package:code_builder/code_builder.dart';
import 'package:path/path.dart' as p;

import '../util/dart_sdk.dart';
import 'terraform_stack.dart';
import 'trigger_config.dart';

/// Orchestrates code-generation, outputting the server entrypoint and the
/// regional Terraform manifest.
Future<void> generateProject({
  required String workspaceRoot,
  required String packageDir,
}) => _DttGenerator(
  workspaceRoot: workspaceRoot,
  packageDir: packageDir,
).generateAll();

class _DttGenerator {
  final String workspaceRoot;
  final String packageDir;

  _DttGenerator({required this.workspaceRoot, required this.packageDir});

  /// Runs all sub-generators, creating/updating target files in the workspace.
  Future<void> generateAll() async {
    final config = await DttConfig.load(packageDir);
    await _generateServer(config);
    await _generateTerraform(config);
  }

  Future<void> _generateServer(DttConfig config) async {
    final binDir = Directory(p.join(packageDir, 'bin'));
    if (!await binDir.exists()) {
      await binDir.create(recursive: true);
    }

    final packageName = p.basename(packageDir);
    final library = Library(
      (l) => l
        ..directives.addAll(
          (_serverImports(
            config,
            packageName,
          ).toList()..sort()).map(Directive.import),
        )
        ..body.add(_serverMain(config)),
    );

    final emitter = DartEmitter(useNullSafetySyntax: true);
    final buffer = StringBuffer()
      ..writeln('// This is an auto-generated file - DO NOT EDIT.')
      ..writeln('// Generated by dtt code generator tool.')
      ..writeln()
      ..writeln(library.accept(emitter).toString());

    final serverFile = File(p.join(binDir.path, 'server.dart'));
    await serverFile.writeAsString(buffer.toString());

    final formatRes = await Process.run(resolveDartExecutable(), [
      'format',
      serverFile.path,
    ]);
    if (formatRes.exitCode != 0) {
      stderr.writeln('Warning: dart format failed:\n${formatRes.stderr}');
    }
  }

  Future<void> _generateTerraform(DttConfig config) async {
    final tfDir = Directory(p.join(workspaceRoot, 'terraform'));
    await tfDir.create(recursive: true);

    final tfJson = DttStack(config).synth().tfJson;
    await File(
      p.join(tfDir.path, 'main.tf.json'),
    ).writeAsString('${const JsonEncoder.withIndent('  ').convert(tfJson)}\n');

    for (final legacy in ['main.tf', 'variables.tf', 'outputs.tf']) {
      final file = File(p.join(tfDir.path, legacy));
      if (await file.exists()) await file.delete();
    }
  }
}

Set<String> _serverImports(DttConfig config, String packageName) => {
  'package:dtt_runtime/dtt_runtime.dart',
  'package:shelf/shelf.dart',
  switch (config.kind) {
    ServiceKind.service => 'package:google_cloud_shelf/google_cloud_shelf.dart',
    ServiceKind.job => 'dart:io',
  },
  ...switch (config.source) {
    ConfigSource.dart => ['package:$packageName/dtt_config.dart'],
    ConfigSource.yaml => [
      'package:google_cloud_events/google_cloud_events.dart',
      for (final trigger in config.triggers)
        'package:$packageName/src/handlers/${toSnakeCase(trigger.handler!)}.dart',
    ],
  },
};

Method _serverMain(DttConfig config) => Method(
  (m) => m
    ..name = 'main'
    ..returns = refer('void')
    ..modifier = MethodModifier.async
    ..body = Block.of([
      declareFinal(
        'router',
      ).assign(CodeExpression(Code(_routerExpression(config)))).statement,
      if (config.source == ConfigSource.dart) _registerDartConfig,
      switch (config.kind) {
        ServiceKind.service => _serveRouter,
        ServiceKind.job => _dispatchJobEvent,
      },
    ]),
);

/// A YAML config names its handlers, so each trigger is registered inline.
/// A Dart config registers its own triggers through [_registerDartConfig].
String _routerExpression(DttConfig config) => [
  'DttEventRouter()',
  if (config.source == ConfigSource.yaml)
    for (final trigger in config.triggers) _yamlRegistration(trigger),
].join();

String _yamlRegistration(TriggerConfig trigger) {
  final pathArg = trigger.path != trigger.meta.defaultPath
      ? "\n      path: '${trigger.path}',"
      : '';
  return '''

    ..registerTrigger(
      trigger: ${trigger.meta.enumName},$pathArg
      handler: ${trigger.handler},
    )''';
}

const _registerDartConfig = Code('''
  for (final trigger in dttConfig.triggers) {
    trigger.register(router);
  }
''');

const _serveRouter = Code('''
  final pipeline = const Pipeline()
      .addMiddleware(logRequests())
      .addHandler(router.handle);
  await serveHandler(pipeline);
''');

/// A job execution handles the single event its workflow passed in.
const _dispatchJobEvent = Code('''
  final env = Platform.environment;
  final response = await router.handle(
    Request(
      'POST',
      Uri.parse('http://localhost\${env['$jobEventPathEnv']}'),
      headers: {'content-type': 'application/cloudevents+json'},
      body: env['$jobCloudEventEnv'],
    ),
  );
  if (response.statusCode != 200) {
    stderr.writeln(await response.readAsString());
    exitCode = 1;
  }
''');
